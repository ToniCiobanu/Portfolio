"""Load the repair CSVs into SQLite, run every query in sql/analysis.sql, and
write the result sets to results.json and results.js (which the web page reads).

    python3 analyze.py          # regenerate results
    python3 analyze.py --check  # fail if results are out of date with the data

Standard library only.
"""
import csv
import json
import re
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).parent


def load_csv(conn, table, path):
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    cols = list(rows[0].keys())
    conn.executemany(
        f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})",
        [[r[c] for c in cols] for r in rows],
    )


def named_queries(sql_text):
    """Split analysis.sql on '-- name: <id>' markers -> {id: sql}."""
    parts = re.split(r"^-- name: (\w+)\s*$", sql_text, flags=re.M)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def run():
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    conn.executescript((HERE / "sql/schema.sql").read_text())
    load_csv(conn, "vehicles", HERE / "data/vehicles.csv")
    load_csv(conn, "repairs", HERE / "data/repairs.csv")

    analysis_sql = (HERE / "sql/analysis.sql").read_text()
    results = {}
    for name, sql in named_queries(analysis_sql).items():
        results[name] = [dict(row) for row in conn.execute(sql)]

    # Sanity checks: the parts must add up to the whole.
    overall = results["overall"][0]
    for group in ("by_vehicle", "by_system", "by_reason", "by_source"):
        total = round(sum(r["savings"] for r in results[group]), 2)
        assert abs(total - overall["savings"]) < 0.01, (group, total, overall["savings"])
    assert overall["repairs"] == len(results["ranked"])

    return {
        "results": results,
        "sql": {
            "schema": (HERE / "sql/schema.sql").read_text(),
            "analysis": analysis_sql,
        },
    }


def main():
    out = run()
    json_text = json.dumps(out["results"], indent=2) + "\n"
    js_text = "// Generated by analyze.py. Do not edit by hand.\nwindow.REPAIRS = " + json.dumps(out) + ";\n"

    targets = {HERE / "results.json": json_text, HERE / "results.js": js_text}
    if "--check" in sys.argv:
        stale = [p.name for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit(f"repair-costs: {', '.join(stale)} out of date; run python3 analyze.py")
        print("repair-costs: results up to date")
        return
    for path, text in targets.items():
        path.write_text(text)
    o = out["results"]["overall"][0]
    print(f"{o['repairs']} repairs | DIY ${o['diy_cost']:,} vs est. ${o['mechanic_estimate']:,} "
          f"| saved ${o['savings']:,} ({o['savings_pct']}%)")


if __name__ == "__main__":
    main()
